export function countryCode(value){
 const term=String(value||'').trim().toLocaleLowerCase('de');
 return countries.find(country=>country.value.toLocaleLowerCase('de')===term||country.code===term)?.code;
}

export function matchesOption(item,query){
 const normalize=value=>String(value||'').toLocaleLowerCase('de').normalize('NFD').replace(/\p{M}/gu,'').replace(/ß/g,'ss').trim();
 const term=normalize(query),text=normalize([item.label,item.searchTerms].filter(Boolean).join(' '));
 // Two-letter country codes must not match inside unrelated names (UK in Neukaledonien).
 return term.length===2?text.split(/[^a-z0-9]+/).includes(term):text.includes(term);
}
